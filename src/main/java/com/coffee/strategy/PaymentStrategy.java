package com.coffee.strategy;

/**
 * ============================================================================
 * 支付策略接口 - 策略模式 (Strategy Pattern) 的实现
 * ============================================================================
 * 
 * 【设计模式说明】
 * 策略模式是一种行为设计模式，它定义了一系列算法（或策略），并将每个算法封装起来，
 * 使它们可以相互替换。策略模式让算法的变化独立于使用算法的客户端。
 * 
 * 【为什么要使用策略模式？】
 * 1. 消除条件判断：避免大量的if-else或switch-case语句
 * 2. 符合开闭原则：新增支付方式只需添加新类，不需修改现有代码
 * 3. 提高可维护性：每种支付方式的逻辑独立，易于理解和修改
 * 4. 运行时切换：可以在运行时动态切换支付策略
 * 
 * 【传统方式的问题】
 * 如果不使用策略模式，支付代码会是这样：
 *   if (paymentType.equals("WECHAT")) {
 *       // 微信支付逻辑
 *       connectToWechatAPI();
 *       processPayment();
 *   } else if (paymentType.equals("ALIPAY")) {
 *       // 支付宝支付逻辑
 *       connectToAlipayAPI();
 *       processPayment();
 *   }
 * 这样会导致：
 * - 代码臃肿，难以阅读
 * - 违反单一职责原则（一个方法做太多事）
 * - 新增支付方式需要修改已有代码（违反开闭原则）
 * - 难以单元测试（无法单独测试某种支付方式）
 * 
 * 【策略模式的优势】
 * 使用策略后：
 *   PaymentStrategy strategy = PaymentFactory.getStrategy("WECHAT");
 *   strategy.pay(amount);
 * 每个支付方式独立成一个类，清晰明了！
 * 
 * 【核心思想】
 * - 定义统一的接口（PaymentStrategy）
 * - 每个具体策略实现该接口（WechatPay, Alipay）
 * - 客户端通过接口调用，不关心具体实现
 * - 可以通过工厂或配置动态选择策略
 * 
 * 【应用场景】
 * - 同一问题有多种不同的解决方案
 * - 需要在运行时选择具体的算法
 * - 算法的实现细节需要对客户端隐藏
 * ============================================================================
 */
public interface PaymentStrategy {
    
    /**
     * 执行支付操作
     * 
     * 这是策略模式的核心方法，所有具体的支付策略都必须实现这个方法。
     * 不同的支付方式会有不同的实现逻辑，但对外提供统一的接口。
     * 
     * @param amount 支付金额
     * @return 支付结果信息
     */
    String pay(double amount);
    
    /**
     * 获取支付方式的名称
     * 
     * @return 支付方式名称
     */
    String getPaymentName();
}
